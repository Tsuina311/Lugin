const SAFE_ID = /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,79}$/;
const MAX_ID_LENGTH = 80;

export const isSafeId = (value: unknown): value is string =>
  typeof value === 'string' && value.length > 0 && value.length <= MAX_ID_LENGTH && SAFE_ID.test(value);

export const sanitizeId = (value: unknown, fallback?: string): string | null => {
  if (isSafeId(value)) return value;
  if (fallback && isSafeId(fallback)) return fallback;
  return null;
};

export const makeSessionId = (now = new Date()): string => {
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `phone-${y}${m}${d}`;
};

export const makeTraceId = (n: number): string => `trace-${String(Math.max(1, n)).padStart(4, '0')}`;

export const normalizeReceiverUrl = (raw: string): string | null => {
  const text = raw.trim().replace(/\/+$/, '');
  if (!text) return null;
  try {
    const parsed = new URL(text);
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return null;
    return parsed.toString().replace(/\/+$/, '');
  } catch {
    return null;
  }
};

export const parsePairInput = (
  raw: string,
): { token: string; url: string } | null => {
  if (typeof raw !== 'string' || !raw.trim()) return null;
  const text = raw.trim();
  try {
    const parsed = new URL(text);
    const pairHost =
      (parsed.protocol === 'lugin:' && parsed.hostname === 'pair-debug') ||
      (parsed.protocol === 'lugin-debug:' && parsed.hostname === 'pair');
    if (pairHost) {
      const url = parsed.searchParams.get('url') ?? '';
      const token = parsed.searchParams.get('token') ?? '';
      if (url && token) return { token, url };
      // URL-only: caller keeps existing token via applyReceiverInput.
      if (url) return { token: '', url };
    }
  } catch {
    /* not a pairing URL */
  }
  return null;
};

export const applyReceiverInput = (
  raw: string,
): { token: string | null; url: string | null } => {
  const paired = parsePairInput(raw);
  if (paired) {
    return {
      token: paired.token ? paired.token : null,
      url: normalizeReceiverUrl(paired.url),
    };
  }
  return { token: null, url: normalizeReceiverUrl(raw) };
};
