#!/usr/bin/env node
/**
 * EAS Build hook: force Yarn Berry before `yarn install`.
 *
 * EAS's image ships Yarn 1.22 and often invokes it by absolute path, so
 * `corepack enable` alone is not enough — Yarn 1 sees `packageManager` and
 * exits. On EAS we overwrite those Yarn 1 entrypoints with a wrapper that execs
 * the committed Berry release (`.yarn/releases` / yarnPath).
 *
 * Locally this script is a no-op (only verifies the release exists) so it never
 * rewrites your machine's Corepack shims.
 *
 * Wired as `eas-build-pre-install` from both root and mobile package.json.
 */

import { execFileSync, spawnSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  realpathSync,
  renameSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = join(scriptDir, '..');

const onEas =
  process.env.EAS_BUILD === 'true' ||
  process.env.EAS_BUILD_RUNNER === 'eas-build' ||
  Boolean(process.env.EAS_BUILD_WORKINGDIR) ||
  process.env.CI === '1' && Boolean(process.env.EAS_BUILD_PROFILE);

function findYarnRelease() {
  const releases = join(root, '.yarn', 'releases');
  if (!existsSync(releases)) {
    throw new Error(`Missing ${releases} — run \`yarn set version 3.8.1\` and commit .yarn/releases`);
  }
  const file = readdirSync(releases).find((f) => /^yarn-.*\.cjs$/.test(f));
  if (!file) throw new Error(`No yarn-*.cjs in ${releases}`);
  return join(releases, file);
}

function whichAllYarn() {
  const out = spawnSync('bash', ['-lc', 'type -a yarn yarnpkg 2>/dev/null || true'], {
    encoding: 'utf8',
  });
  const paths = [];
  for (const line of (out.stdout || '').split('\n')) {
    const m = line.match(/(?:yarn|yarnpkg) is\s+(\S+)/) || line.match(/(\/\S*yarn(?:pkg)?)\s*$/);
    if (m?.[1] && existsSync(m[1])) paths.push(m[1]);
  }
  for (const candidate of [
    '/usr/local/bin/yarn',
    '/usr/local/bin/yarnpkg',
    '/usr/bin/yarn',
    '/usr/bin/yarnpkg',
    '/home/expo/.npm-global/bin/yarn',
    join(process.env.HOME || '', '.yarn', 'bin', 'yarn'),
  ]) {
    if (candidate && existsSync(candidate)) paths.push(candidate);
  }
  return [...new Set(paths.map((p) => {
    try {
      return realpathSync(p);
    } catch {
      return p;
    }
  }))];
}

const release = findYarnRelease();
const ver = execFileSync(process.execPath, [release, '--version'], {
  cwd: root,
  encoding: 'utf8',
}).trim();
console.log(`Yarn Berry release: ${ver} (${release})`);

if (!onEas) {
  console.log('Not an EAS Build environment — skipping yarn binary replacement.');
  process.exit(0);
}

const wrapper = `#!/bin/sh
# Generated by scripts/eas-build-pre-install.mjs on EAS Build — do not edit.
exec "${process.execPath}" "${release}" "$@"
`;

for (const dest of whichAllYarn()) {
  try {
    const bak = `${dest}.classic.bak`;
    if (!existsSync(bak)) {
      try {
        renameSync(dest, bak);
      } catch {
        /* overwrite in place */
      }
    }
    writeFileSync(dest, wrapper, { mode: 0o755 });
    chmodSync(dest, 0o755);
    console.log(`Replaced yarn at ${dest} → ${release}`);
  } catch (err) {
    console.warn(`Could not replace ${dest}: ${err instanceof Error ? err.message : err}`);
  }
}

const binDir = join(root, '.eas-yarn-bin');
mkdirSync(binDir, { recursive: true });
writeFileSync(join(binDir, 'yarn'), wrapper, { mode: 0o755 });
chmodSync(join(binDir, 'yarn'), 0o755);

const check = spawnSync('yarn', ['--version'], { cwd: root, encoding: 'utf8' });
console.log(`PATH yarn --version → ${(check.stdout || check.stderr || '').trim()} (status ${check.status})`);
if (check.status !== 0 || !(check.stdout || '').includes('3.')) {
  console.warn('WARNING: PATH yarn is still not Berry after replacement.');
}
