export const parsePairInput = (raw) => {
  if (typeof raw !== 'string' || !raw.trim()) return null;
  const text = raw.trim();
  try {
    const parsed = new URL(text);
    const pairHost =
      (parsed.protocol === 'lugin:' && parsed.hostname === 'pair-debug') ||
      (parsed.protocol === 'lugin-debug:' && (parsed.hostname === 'pair' || parsed.pathname === '//pair'));
    if (pairHost) {
      const url = parsed.searchParams.get('url') ?? '';
      const token = parsed.searchParams.get('token') ?? '';
      if (url && token) return { token, url };
    }
  } catch {
    /* not a URL */
  }
  return null;
};

export const decodeFilePayload = (name, file) => {
  if (!file || typeof file !== 'object') return { ok: false, reason: 'missing file' };
  const expectedMime = ALLOWED_FILES[name];
  if (!expectedMime) return { ok: false, reason: `unexpected file ${name}` };
  const mime = typeof file.mime === 'string' ? file.mime : expectedMime;
  if (mime !== expectedMime) return { ok: false, reason: `invalid mime for ${name}` };

  let bytes;
  if (typeof file.text === 'string') {
    bytes = Buffer.from(file.text, 'utf8');
  } else if (typeof file.base64 === 'string') {
    try {
      bytes = Buffer.from(file.base64, 'base64');
    } catch {
      return { ok: false, reason: `invalid base64 for ${name}` };
    }
  } else {
    return { ok: false, reason: `no payload for ${name}` };
  }

  if (expectedMime === 'image/png') {
    if (bytes.length > MAX_PNG_BYTES) return { ok: false, reason: `png too large: ${name}` };
    if (bytes.length < PNG_MAGIC.length || !bytes.subarray(0, 8).equals(PNG_MAGIC)) {
      return { ok: false, reason: `not a png: ${name}` };
    }
  } else if (expectedMime === 'image/jpeg') {
    if (bytes.length > MAX_PNG_BYTES) return { ok: false, reason: `jpeg too large: ${name}` };
    if (bytes.length < 3 || bytes[0] !== 0xff || bytes[1] !== 0xd8 || bytes[2] !== 0xff) {
      return { ok: false, reason: `not a jpeg: ${name}` };
    }
  } else {
    if (bytes.length > MAX_JSON_BYTES) return { ok: false, reason: `text too large: ${name}` };
  }
  return { bytes, mime: expectedMime, ok: true };
};

export const validateUploadBody = (body) => {
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    return { ok: false, reason: 'invalid body' };
  }
  const sessionId = sanitizeId(body.sessionId);
  const traceId = sanitizeId(body.traceId);
  if (!sessionId) return { ok: false, reason: 'invalid sessionId' };
  if (!traceId) return { ok: false, reason: 'invalid traceId' };
  const files = body.files;
  if (!files || typeof files !== 'object' || Array.isArray(files)) {
    return { ok: false, reason: 'files required' };
  }
  const names = Object.keys(files);
  if (!names.length) return { ok: false, reason: 'files empty' };
  const decoded = {};
  let total = 0;
  for (const name of names) {
    if (name.includes('/') || name.includes('\\') || name.includes('..')) {
      return { ok: false, reason: 'path traversal' };
    }
    const one = decodeFilePayload(name, files[name]);
    if (!one.ok) return one;
    total += one.bytes.length;
    if (total > MAX_BUNDLE_BYTES) return { ok: false, reason: 'bundle too large' };
    decoded[name] = one;
  }
  return {
    ok: true,
    sessionId,
    traceId,
    createdAt: typeof body.createdAt === 'string' ? body.createdAt : new Date().toISOString(),
    device: typeof body.device === 'string' ? body.device.slice(0, 200) : null,
    appStamp: typeof body.appStamp === 'string' ? body.appStamp.slice(0, 120) : null,
    runtimeFingerprint:
      typeof body.runtimeFingerprint === 'string' ? body.runtimeFingerprint.slice(0, 80) : null,
    scannerPhase: typeof body.scannerPhase === 'string' ? body.scannerPhase.slice(0, 40) : null,
    traceType: typeof body.traceType === 'string' ? body.traceType.slice(0, 40) : 'unknown',
    files: decoded,
  };
};

export const sampleCountFromFiles = (files) => {
  const geo = files['geometry-trace.json'];
  if (!geo?.bytes) return null;
  try {
    const json = JSON.parse(geo.bytes.toString('utf8'));
    return json.meta?.sampleCount ?? json.samples?.length ?? null;
  } catch {
    return null;
  }
};

