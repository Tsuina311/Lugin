const SAFE_ID = /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,79}$/;
const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

export const isSafeId = (value) =>
  typeof value === 'string' && value.length > 0 && value.length <= MAX_ID_LENGTH && SAFE_ID.test(value);

export const sanitizeId = (value, fallback) => {
  if (isSafeId(value)) return value;
  if (fallback && isSafeId(fallback)) return fallback;
  return null;
};

export const timingSafeEqualToken = (expected, provided) => {
  if (typeof expected !== 'string' || typeof provided !== 'string') return false;
  const a = Buffer.from(expected, 'utf8');
  const b = Buffer.from(provided, 'utf8');
  if (a.length !== b.length) {
    // Compare anyway so length leaks are not a cheap oracle.
    const dummy = Buffer.alloc(a.length);
    b.copy(dummy, 0, 0, Math.min(b.length, dummy.length));
    timingSafeEqual(a, dummy);
    return false;
  }
  return timingSafeEqual(a, b);
};

export const parseBearer = (header) => {
  if (typeof header !== 'string') return null;
  const m = header.match(/^Bearer\s+(\S+)\s*$/i);
  return m ? m[1] : null;
};

