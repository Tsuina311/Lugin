#!/usr/bin/env node
/**
 * Bake mobile/build-stamp.json from the monorepo git stamp.
 *
 * EAS Build uploads omit `.git/` (.easignore), so app.config.ts cannot count
 * commits on the builder. Write the stamp locally / in CI before `eas build`
 * or `eas update` so the APK and Settings panel show the real version.
 */

import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'mobile', 'build-stamp.json');
const versionSource = join(root, 'mobile', 'src', 'phoneVersion.ts');
const publishes = join(root, 'mobile', 'phone-publish.json');

const readPublishCount = () => {
  if (!existsSync(publishes)) return 0;
  try {
    const parsed = JSON.parse(readFileSync(publishes, 'utf8'));
    return Number.isInteger(parsed.n) && parsed.n > 0 ? parsed.n : 0;
  } catch {
    return 0;
  }
};

// `--bump` runs only when JS is actually sent to the phone. The git commit
// count stays put across those publishes, so without this the Settings line
// never changes and a fix looks like it did not apply.
let phonePublish = readPublishCount();
if (process.argv.includes('--bump')) {
  phonePublish += 1;
  writeFileSync(publishes, `${JSON.stringify({ n: phonePublish }, null, 2)}\n`);
}

const raw = execSync(
  `node --experimental-strip-types -e "import { buildVersion } from './build/version.ts'; process.stdout.write(JSON.stringify(buildVersion('./')))"`,
  { cwd: root, encoding: 'utf8' },
);
const stamp = JSON.parse(raw);
if (phonePublish > 0) {
  stamp.label = `v${stamp.version}.${phonePublish} · ${stamp.id}`;
}
writeFileSync(out, `${JSON.stringify(stamp, null, 2)}\n`);
// In the JS bundle, not only the Expo manifest. Settings reads this import, so
// the line on screen is the copy that is actually running.
writeFileSync(
  versionSource,
  `// Generated by scripts/write-mobile-build-stamp.mjs. Do not edit.\nexport const PHONE_VERSION = ${JSON.stringify(stamp.label)};\n`,
);
console.log(`Wrote ${out} (${stamp.label})`);
